func generateTypeScript() string {
	knownNames := make(map[reflect.Type]string, len(typeSpecs))
	for _, spec := range typeSpecs {
		knownNames[spec.goType] = spec.tsName
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by cmd/gen-ts-types; DO NOT EDIT.\n")
	buf.WriteString("// Run `bun run generate:types` to regenerate.\n\n")
	buf.WriteString(`export type AccountType = "credit_card" | "debit_card" | "digital_wallet"` + "\n")
	buf.WriteString(`export type AccountIdentifierKind = "card_last4" | "bank_account" | "alias"` + "\n")
	buf.WriteString(`export type AccountStatus = "provisional" | "confirmed"` + "\n")

	for _, spec := range typeSpecs {
		buf.WriteString("\nexport interface ")
		buf.WriteString(spec.tsName)
		buf.WriteString(" {\n")
		writeStructFields(&buf, spec.goType, spec.overrides, knownNames)
		buf.WriteString("}\n")
	}

	return buf.String()
}

func writeStructFields(buf *bytes.Buffer, t reflect.Type, overrides map[string]string, knownNames map[reflect.Type]string) {
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		if !f.IsExported() {
			continue
		}
		jsonTag := f.Tag.Get("json")
		if jsonTag == "-" {
			continue
		}
		if f.Anonymous && f.Type.Kind() == reflect.Struct && jsonTag == "" {
			writeStructFields(buf, f.Type, overrides, knownNames)
			continue
		}

		name := f.Name
		optional := false
		if jsonTag != "" {
			parts := strings.Split(jsonTag, ",")
			if parts[0] != "" {
				name = parts[0]
			}
			for _, opt := range parts[1:] {
				if opt == "omitempty" {
					optional = true
				}
			}
		}

		tsType := goTypeToTS(f.Type, knownNames)
		if override, ok := overrides[name]; ok {
			tsType = override
		}

		optMark := ""
		if optional {
			optMark = "?"
		}
		fmt.Fprintf(buf, "  %s%s: %s\n", name, optMark, tsType)
	}
}

func goTypeToTS(t reflect.Type, knownNames map[reflect.Type]string) string {
	if t.Kind() == reflect.Ptr {
		return goTypeToTS(t.Elem(), knownNames) + " | null"
	}
	if name, ok := knownNames[t]; ok {
		return name
	}
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Slice, reflect.Array:
		return goTypeToTS(t.Elem(), knownNames) + "[]"
	case reflect.Map:
		return "Record<string, " + goTypeToTS(t.Elem(), knownNames) + ">"
	default:
		return "unknown"
	}
}

func main() {
	outPath := flag.String("out", "lib/api/types.generated.ts", "output TypeScript file path")
	check := flag.Bool("check", false, "verify that the generated file is up to date without modifying it")
	flag.Parse()

	generated := generateTypeScript()

	if *check {
		existing, err := os.ReadFile(*outPath)
		if err != nil {
			fmt.Fprintf(os.Stderr, "check failed: could not read %s: %v\n", *outPath, err)
			os.Exit(1)
		}
		if string(existing) != generated {
			fmt.Fprintf(os.Stderr, "check failed: %s is out of date; run `bun run generate:types`\n", *outPath)
			os.Exit(1)
		}
		return
	}

	if err := os.MkdirAll(filepath.Dir(*outPath), 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "failed to create output directory: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*outPath, []byte(generated), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "failed to write %s: %v\n", *outPath, err)
		os.Exit(1)
	}
}
