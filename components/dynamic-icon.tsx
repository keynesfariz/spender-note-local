export function DynamicIcon({
  name,
  className,
}: {
  name?: string | null
  className?: string
}) {
  const Icon = (name ? CATEGORY_ICON_MAP[name] : undefined) ?? Tag
  return createElement(Icon, {
    className: cn("size-4 shrink-0", className),
    "aria-hidden": true,
  })
}
